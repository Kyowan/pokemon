def assign_region(pid, types):
    """
    지역 4곳:
    - forest (숲): 풀, 벌레, 독(자연/생물형), 페어리, 비행
    - city (도시): 전기, 에스퍼, 격투, 강철, 고스트, 노말(도시형), 독(공해형: 질퍽이/또가스)
    - desert (사막): 불꽃, 땅, 바위, 드래곤, 악
    - sea (바다): 물, 얼음
    """
    primary = types[0]
    secondary = types[1] if len(types) > 1 else None

    # 물·얼음은 바다 우선 (단, 암나이트~투구푸스 등 고대화석/물 포켓몬도 바다에 배치)
    if "물" in types or "얼음" in types:
        return "sea"
    # 불꽃·땅·바위·드래곤·악은 사막 우선
    if primary in ("불꽃", "땅", "바위", "드래곤", "악") or secondary in ("땅", "바위", "드래곤"):
        return "desert"
    # 풀·벌레는 숲
    if "풀" in types or "벌레" in types:
        return "forest"
    # 공해형 독 포켓몬(질퍽이, 질뻐기, 또가스, 또도가스)은 도시
    if pid in (88, 89, 109, 110):
        return "city"
    # 전기, 에스퍼, 격투, 강철, 고스트는 도시
    if primary in ("전기", "에스퍼", "격투", "강철", "고스트"):
        return "city"
    # 비행이 포함된 노말/독(구구, 깨비참, 주뱃, 파오리, 두두 등)과 독(아보, 니드런)은 숲
    if "비행" in types or primary == "독" or pid in (35, 36, 39, 40):
        return "forest"
    # 나머지 노말(꼬렛, 나옹, 내루미, 럭키, 캥카, 켄타로스, 메타몽, 이브이, 폴리곤, 잠만보, 레지기가스, 아르세우스)은 도시
    return "city"


def build_pokemon_list():
    all_raw = GEN1_POKEMON + EXTRA_LEGENDARIES
    result = []
    for pid, name, types, is_legendary in all_raw:
        region = assign_region(pid, types)
        result.append({
            "id": pid,
            "name": name,
            "types": types,
            "region": region,
            "isLegendary": is_legendary,
            "image": f"https://raw.githubusercontent.com/PokeAPI/sprites/master/sprites/pokemon/other/official-artwork/{pid}.png",
        })
    return result


